// localStorage JSON helpers. Storage can be unavailable (private mode, blocked site data):
// reads then return the fallback and writes are skipped, so progress just doesn't persist.
export function loadJSON(key, fallback) {
  try {
    const raw = localStorage.getItem(key);
    return raw === null ? fallback : JSON.parse(raw);
  } catch {
    return fallback;
  }
}

export function saveJSON(key, value) {
  try {
    localStorage.setItem(key, JSON.stringify(value));
  } catch {
    // ignore
  }
}
